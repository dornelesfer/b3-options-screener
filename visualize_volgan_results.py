#!/usr/bin/env python3
"""
Visualize VolGAN Results - Brazilian Options Volatility Surfaces
Shows the synthetic volatility surfaces generated by our trained model
"""
import sys
from pathlib import Path
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns
from mpl_toolkits.mplot3d import Axes3D
import torch

# Add src to path
sys.path.append(str(Path(__file__).parent / 'src'))

# Import VolGAN components
from volgan_model import VolGANTrainer

# Setup plotting style
plt.style.use('seaborn-v0_8')
sns.set_palette("husl")

def load_trained_model():
    """Load the trained VolGAN model"""
    print("📥 Loading trained VolGAN model...")
    
    # Initialize trainer
    trainer = VolGANTrainer(
        latent_dim=100,
        batch_size=128,
        generator_lr=0.0002,
        discriminator_lr=0.0002
    )
    
    # Load the trained model
    model_path = "models/volgan_final.pth"
    if Path(model_path).exists():
        trainer.load_model(model_path)
        print(f"✅ Model loaded from: {model_path}")
        return trainer
    else:
        raise FileNotFoundError(f"Model not found: {model_path}")

def load_generated_samples():
    """Load the generated samples"""
    print("📥 Loading generated samples...")
    
    samples_path = "results/generated_samples.npy"
    if Path(samples_path).exists():
        samples = np.load(samples_path)
        print(f"✅ Loaded {len(samples)} generated samples")
        return samples
    else:
        raise FileNotFoundError(f"Samples not found: {samples_path}")

def load_training_data_stats():
    """Load training data statistics for denormalization"""
    print("📊 Loading training data statistics...")
    
    training_file = Path('data/processed/volgan_training_data.csv')
    if training_file.exists():
        training_data = pd.read_csv(training_file)
        
        # Calculate statistics for denormalization
        stats = {
            'k_mean': training_data['k'].mean(),
            'k_std': training_data['k'].std(),
            'T_mean': training_data['T'].mean(),
            'T_std': training_data['T'].std(),
            'iv_mean': training_data['iv'].mean(),
            'iv_std': training_data['iv'].std()
        }
        
        print("✅ Training data statistics loaded")
        return stats
    else:
        print("⚠️  Training data not found, using normalized values")
        return None

def denormalize_samples(samples, stats):
    """Denormalize the generated samples"""
    if stats is None:
        return samples
    
    denorm_samples = samples.copy()
    denorm_samples[:, 0] = samples[:, 0] * stats['k_std'] + stats['k_mean']  # k
    denorm_samples[:, 1] = samples[:, 1] * stats['T_std'] + stats['T_mean']  # T
    denorm_samples[:, 2] = samples[:, 2] * stats['iv_std'] + stats['iv_mean']  # iv
    
    return denorm_samples

def generate_new_samples(trainer, num_samples=100):
    """Generate new samples using the trained model"""
    print(f"🎨 Generating {num_samples} new volatility surfaces...")
    
    trainer.generator.eval()
    with torch.no_grad():
        # Generate random latent vectors
        z = torch.randn(num_samples, trainer.latent_dim).to(trainer.device)
        
        # Generate samples
        generated_samples = trainer.generator(z)
        
        return generated_samples.cpu().numpy()

def plot_volatility_surfaces(samples, title="Generated Volatility Surfaces", stats=None):
    """Plot the volatility surfaces in 3D"""
    print("📊 Creating 3D volatility surface plots...")
    
    # Denormalize if stats provided
    if stats is not None:
        samples = denormalize_samples(samples, stats)
        x_label, y_label, z_label = "Log Moneyness (k)", "Time to Maturity (T)", "Implied Volatility (σ)"
    else:
        x_label, y_label, z_label = "Normalized k", "Normalized T", "Normalized IV"
    
    # Create figure with subplots
    fig = plt.figure(figsize=(20, 12))
    
    # Plot 1: 3D scatter plot
    ax1 = fig.add_subplot(2, 3, 1, projection='3d')
    scatter = ax1.scatter(samples[:, 0], samples[:, 1], samples[:, 2], 
                          c=samples[:, 2], cmap='viridis', alpha=0.6)
    ax1.set_xlabel(x_label)
    ax1.set_ylabel(y_label)
    ax1.set_zlabel(z_label)
    ax1.set_title("3D Volatility Surface Scatter")
    plt.colorbar(scatter, ax=ax1, shrink=0.5)
    
    # Plot 2: k vs IV
    ax2 = fig.add_subplot(2, 3, 2)
    ax2.scatter(samples[:, 0], samples[:, 2], alpha=0.6, c=samples[:, 2], cmap='viridis')
    ax2.set_xlabel(x_label)
    ax2.set_ylabel(z_label)
    ax2.set_title("Log Moneyness vs Implied Volatility")
    
    # Plot 3: T vs IV
    ax3 = fig.add_subplot(2, 3, 3)
    ax3.scatter(samples[:, 1], samples[:, 2], alpha=0.6, c=samples[:, 2], cmap='viridis')
    ax3.set_xlabel(y_label)
    ax3.set_ylabel(z_label)
    ax3.set_title("Time to Maturity vs Implied Volatility")
    
    # Plot 4: k vs T
    ax4 = fig.add_subplot(2, 3, 4)
    scatter4 = ax4.scatter(samples[:, 0], samples[:, 1], c=samples[:, 2], cmap='viridis', alpha=0.6)
    ax4.set_xlabel(x_label)
    ax4.set_ylabel(y_label)
    ax4.set_title("Log Moneyness vs Time to Maturity")
    plt.colorbar(scatter4, ax=ax4, shrink=0.5)
    
    # Plot 5: IV distribution
    ax5 = fig.add_subplot(2, 3, 5)
    ax5.hist(samples[:, 2], bins=30, alpha=0.7, color='skyblue', edgecolor='black')
    ax5.set_xlabel(z_label)
    ax5.set_ylabel("Frequency")
    ax5.set_title("Implied Volatility Distribution")
    
    # Plot 6: 2D heatmap (k vs T)
    ax6 = fig.add_subplot(2, 3, 6)
    
    # Create 2D histogram
    k_bins = np.linspace(samples[:, 0].min(), samples[:, 0].max(), 20)
    T_bins = np.linspace(samples[:, 1].min(), samples[:, 1].max(), 20)
    
    H, xedges, yedges = np.histogram2d(samples[:, 0], samples[:, 1], bins=[k_bins, T_bins])
    
    im = ax6.imshow(H.T, origin='lower', extent=[xedges[0], xedges[-1], yedges[0], yedges[-1]], 
                     aspect='auto', cmap='viridis')
    ax6.set_xlabel(x_label)
    ax6.set_ylabel(y_label)
    ax6.set_title("2D Density Heatmap (k vs T)")
    plt.colorbar(im, ax=ax6, shrink=0.5)
    
    plt.tight_layout()
    plt.suptitle(title, fontsize=16, y=1.02)
    
    return fig

def plot_training_losses(trainer):
    """Plot the training losses"""
    print("📈 Plotting training losses...")
    
    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(15, 6))
    
    # Generator losses
    ax1.plot(trainer.g_losses, label='Generator Loss', color='blue', linewidth=2)
    ax1.set_xlabel('Epoch')
    ax1.set_ylabel('Loss')
    ax1.set_title('Generator Training Loss')
    ax1.legend()
    ax1.grid(True, alpha=0.3)
    
    # Discriminator losses
    ax2.plot(trainer.d_losses, label='Discriminator Loss', color='red', linewidth=2)
    ax2.set_xlabel('Epoch')
    ax2.set_ylabel('Loss')
    ax2.set_title('Discriminator Training Loss')
    ax2.legend()
    ax2.grid(True, alpha=0.3)
    
    plt.tight_layout()
    return fig

def main():
    """Main visualization function"""
    print("🎯 VolGAN Results Visualization")
    print("=" * 50)
    
    try:
        # Load components
        trainer = load_trained_model()
        generated_samples = load_generated_samples()
        training_stats = load_training_data_stats()
        
        # Generate new samples
        new_samples = generate_new_samples(trainer, num_samples=500)
        
        # Create visualizations
        print("\n📊 Creating visualizations...")
        
        # Plot 1: Generated samples
        fig1 = plot_volatility_surfaces(
            generated_samples, 
            title="Trained VolGAN: Generated Brazilian Options Volatility Surfaces",
            stats=training_stats
        )
        fig1.savefig("results/generated_volatility_surfaces.png", dpi=300, bbox_inches='tight')
        print("💾 Saved: generated_volatility_surfaces.png")
        
        # Plot 2: New samples
        fig2 = plot_volatility_surfaces(
            new_samples, 
            title="Trained VolGAN: Newly Generated Volatility Surfaces",
            stats=training_stats
        )
        fig2.savefig("results/new_volatility_surfaces.png", dpi=300, bbox_inches='tight')
        print("💾 Saved: new_volatility_surfaces.png")
        
        # Plot 3: Training losses
        fig3 = plot_training_losses(trainer)
        fig3.savefig("results/training_losses.png", dpi=300, bbox_inches='tight')
        print("💾 Saved: training_losses.png")
        
        # Show plots
        plt.show()
        
        # Print summary statistics
        print("\n📋 Summary Statistics:")
        print(f"Generated samples shape: {generated_samples.shape}")
        print(f"New samples shape: {new_samples.shape}")
        
        if training_stats:
            denorm_gen = denormalize_samples(generated_samples, training_stats)
            print(f"\nDenormalized ranges:")
            print(f"Log Moneyness (k): {denorm_gen[:, 0].min():.3f} to {denorm_gen[:, 0].max():.3f}")
            print(f"Time to Maturity (T): {denorm_gen[:, 1].min():.3f} to {denorm_gen[:, 1].max():.3f}")
            print(f"Implied Volatility (σ): {denorm_gen[:, 2].min():.3f} to {denorm_gen[:, 2].max():.3f}")
        
        print("\n✅ Visualization complete! Check the 'results' folder for saved plots.")
        
    except Exception as e:
        print(f"❌ Visualization failed: {e}")
        raise

if __name__ == "__main__":
    main()

